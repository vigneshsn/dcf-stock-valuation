import { Component, computed, input, signal } from '@angular/core';
import { StatementYear } from '../models/analysis';

type StatementKey = 'income' | 'balance' | 'cash';
type Unit = 'crore' | 'percent' | 'ratio';

interface LineItem {
    label: string;
    unit: Unit;
    explain: string;
    values: (number | null)[];
}

interface Bar {
    x: number;
    y: number;
    h: number;
    neg: boolean;
}

interface Statement {
    key: StatementKey;
    title: string;
    what: string;
    takeaway: string | null;
    items: (LineItem & { bars: Bar[]; latest: number | null })[];
}

const CHART_HEIGHT = 44;

const STATEMENTS: Record<StatementKey, {
    title: string;
    what: string;
    takeaway: (years: StatementYear[]) => string | null;
    items: (Omit<LineItem, 'values'> & { metric: keyof StatementYear })[];
}> = {
    income: {
        title: 'Income statement',
        what: 'How much the company sold in each year and how much of it was left as profit.',
        takeaway: incomeTakeaway,
        items: [
            { metric: 'revenue', label: 'Revenue (₹ cr)', unit: 'crore', explain: 'Total sales in the year.' },
            { metric: 'ebitda', label: 'EBITDA (₹ cr)', unit: 'crore', explain: 'Operating profit before interest, tax, depreciation and amortisation.' },
            { metric: 'netProfit', label: 'Net profit (₹ cr)', unit: 'crore', explain: 'What is left for shareholders after every expense.' },
            { metric: 'netMargin', label: 'Net margin', unit: 'percent', explain: 'Net profit as a share of revenue.' }
        ]
    },
    balance: {
        title: 'Balance sheet',
        what: 'What the company owns (assets) and owes (borrowings) at each year end, and what belongs to shareholders (equity).',
        takeaway: balanceTakeaway,
        items: [
            { metric: 'totalAssets', label: 'Total assets (₹ cr)', unit: 'crore', explain: 'Everything the company owns.' },
            { metric: 'borrowings', label: 'Borrowings (₹ cr)', unit: 'crore', explain: 'Money owed to lenders.' },
            { metric: 'equity', label: 'Shareholder equity (₹ cr)', unit: 'crore', explain: 'Assets minus liabilities: the owners’ stake.' },
            { metric: 'debtToEquity', label: 'Debt / equity', unit: 'ratio', explain: 'Borrowings for every rupee of shareholder equity.' }
        ]
    },
    cash: {
        title: 'Cash flow',
        what: 'The cash that actually came in from the business and went out on investment (capex) in each year.',
        takeaway: cashTakeaway,
        items: [
            { metric: 'operatingCashFlow', label: 'Cash from operations (₹ cr)', unit: 'crore', explain: 'Cash generated by the day-to-day business.' },
            { metric: 'capex', label: 'Capex (₹ cr)', unit: 'crore', explain: 'Cash spent on plants, equipment and other long-term assets.' },
            { metric: 'freeCashFlow', label: 'Free cash flow (₹ cr)', unit: 'crore', explain: 'Cash from operations minus capex.' },
            { metric: 'cashConversion', label: 'Cash conversion', unit: 'percent', explain: 'Cash from operations as a share of net profit; around 100% means profit arrives as cash.' }
        ]
    }
};

const KEYS: StatementKey[] = ['income', 'balance', 'cash'];

/** Curated financial statements over up to five fiscal years: facts and trends, no judgement. */
@Component({
    selector: 'app-financial-statements',
    standalone: true,
    templateUrl: './financial-statements.component.html',
    styleUrls: ['./financial-statements.component.css']
})
export class FinancialStatementsComponent {
    /** Oldest first. */
    readonly years = input.required<StatementYear[]>();
    /** Dense mode: number tables only, without explanations or charts. */
    readonly dense = input(false);

    private readonly openTables = signal<ReadonlySet<StatementKey>>(new Set());

    readonly statements = computed<Statement[]>(() => {
        const years = this.years();
        return KEYS.map((key) => ({
            key,
            title: STATEMENTS[key].title,
            what: STATEMENTS[key].what,
            takeaway: STATEMENTS[key].takeaway(years),
            items: STATEMENTS[key].items.map(({ metric, ...item }) => {
                const values = years.map((y) => y[metric]);
                return { ...item, values, bars: bars(values), latest: values[values.length - 1] ?? null };
            })
        }));
    });

    readonly latestYear = computed(() => this.years().at(-1)?.year ?? null);

    isTableOpen(key: StatementKey): boolean {
        return this.dense() || this.openTables().has(key);
    }

    toggleTable(key: StatementKey): void {
        const next = new Set(this.openTables());
        if (!next.delete(key)) {
            next.add(key);
        }
        this.openTables.set(next);
    }

    format(value: number | null, unit: Unit): string {
        if (value == null) {
            return '—';
        }
        if (unit === 'percent') {
            return `${value.toFixed(1)}%`;
        }
        if (unit === 'ratio') {
            return `${value.toFixed(2)}×`;
        }
        return Math.round(value).toLocaleString('en-IN');
    }
}

function bars(values: (number | null)[]): Bar[] {
    const max = Math.max(1e-9, ...values.map((v) => Math.abs(v ?? 0)));
    return values.flatMap((v, i) => {
        if (v == null) {
            return [];
        }
        const h = Math.max(2, (Math.abs(v) / max) * CHART_HEIGHT);
        return [{ x: i * 22 + 2, y: CHART_HEIGHT - h, h, neg: v < 0 }];
    });
}

const pct = (v: number) => `${Math.abs(v).toFixed(1)}%`;

/** First and last years where the metric is known, or null when fewer than two. */
function span(years: StatementYear[], metric: keyof StatementYear): [StatementYear, StatementYear] | null {
    const known = years.filter((y) => y[metric] != null);
    return known.length >= 2 ? [known[0], known[known.length - 1]] : null;
}

function joinSentences(parts: (string | null)[]): string | null {
    const kept = parts.filter((p): p is string => p != null);
    return kept.length ? kept.join(' ') : null;
}

function incomeTakeaway(years: StatementYear[]): string | null {
    let revenue: string | null = null;
    const r = span(years.filter((y) => (y.revenue ?? 0) > 0), 'revenue');
    if (r) {
        const [first, last] = r;
        const cagr = (Math.pow(last.revenue! / first.revenue!, 1 / (last.year - first.year)) - 1) * 100;
        revenue = `Revenue ${cagr >= 0 ? 'grew' : 'fell'} ${pct(cagr)} a year from FY${first.year} to FY${last.year}`;
        const prior = years.find((y) => y.year === last.year - 1);
        if (prior?.revenue && last.year - first.year > 1) {
            const change = (last.revenue! / prior.revenue - 1) * 100;
            if (Math.sign(change) !== Math.sign(cagr)) {
                revenue += `; it ${change >= 0 ? 'grew' : 'fell'} ${pct(change)} in FY${last.year}`;
            }
        }
        revenue += '.';
    }
    const m = span(years, 'netMargin');
    const margin = m ? `Net margin went from ${m[0].netMargin!.toFixed(1)}% to ${m[1].netMargin!.toFixed(1)}%.` : null;
    return joinSentences([revenue, margin]);
}

function balanceTakeaway(years: StatementYear[]): string | null {
    const d = span(years, 'debtToEquity');
    if (!d) {
        return null;
    }
    const borrowings = years.map((y) => y.borrowings);
    let trend = '';
    if (borrowings.length >= 3 && borrowings.every((b) => b != null)) {
        const steps = borrowings.slice(1).map((b, i) => b! - borrowings[i]!);
        trend = steps.every((s) => s > 0) ? '; borrowings rose every year' : steps.every((s) => s < 0) ? '; borrowings fell every year' : '';
    }
    return `Debt / equity went from ${d[0].debtToEquity!.toFixed(2)}× in FY${d[0].year} to ${d[1].debtToEquity!.toFixed(2)}× in FY${d[1].year}${trend}.`;
}

function cashTakeaway(years: StatementYear[]): string | null {
    const cfo = years.filter((y) => y.operatingCashFlow != null);
    const fcf = years.filter((y) => y.freeCashFlow != null);
    const conversion = years.flatMap((y) => (y.cashConversion == null ? [] : [y.cashConversion]));
    if (cfo.length < 2) {
        return null;
    }
    let text = `Cash from operations was positive in ${cfo.filter((y) => y.operatingCashFlow! > 0).length} of ${cfo.length} years`;
    if (fcf.length >= 2) {
        text += ` and free cash flow in ${fcf.filter((y) => y.freeCashFlow! > 0).length} of ${fcf.length}`;
    }
    if (conversion.length >= 2) {
        text += `; cash conversion averaged ${Math.round(conversion.reduce((a, b) => a + b, 0) / conversion.length)}%`;
    }
    return `${text}.`;
}
